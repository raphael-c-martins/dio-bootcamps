### Fatiamento de strings ###

nome = "Raphael Silva Costa"

nome[0]
# "R"

nome[1]
# "a"

nome[0:5]
# "Rapha"

nome[2:7]
# "phael"

nome[0:18:3]
# "Rh aot"

nome[:]
# "Raphael Silva Costa"

nome[-1]
# "a"

nome[-2]
# "t"

nome[-3: ]
# "sta"

nome[::-1]
# "atsoC avliS leahpaR"