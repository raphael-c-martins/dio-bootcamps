### Soma
saldo = 500
saldo += 200

print(saldo)
# 700   

### Subtração
saldo = 400
saldo -= 50

print(saldo)
# 350   

### Multiplicação
saldo *= 2

print(saldo)
# 700   

### Divisão
saldo /= 2

print(saldo)
# 350.0   

### Divisão inteira
saldo //= 2

print(saldo)
# 175.0  

### Módulo
saldo %= 2

print(saldo)
# 1.0  

### Potência
saldo **= 2

print(saldo)
# 1.0